const content = `
# Переменные и типы данных в Java

## 1. Что такое переменная

Переменная — это **имя**, под которым мы сохраняем значение, чтобы позже использовать его в программе.

Например:

\`\`\`
int age = 25;
\`\`\`
Здесь:
- \`int\` — тип переменной (целое число),
- \`age\` — имя переменной,
- \`25\` — значение, которое сохраняется.

## 2. Типы данных в Java
Java — строготипизированный язык, то есть каждому значению должен соответствовать свой тип.
### Основные примитивные типы
| Тип       | Что хранит                                 | Пример    |
| --------- | ------------------------------------------ | --------- |
| \`int\`     | Целые числа                                | \`10\`      |
| \`double\`  | Дробные числа                              | \`3.14\`    |
| \`boolean\` | Правда или ложь                            | \`true\`    |
| \`char\`    | Один символ                                | \`'A'\`     |
| \`String\`  | Текст (не примитив, но часто используется) | \`"Hello"\` |

## 3. Объявление переменных
\`\`\`
int number;
boolean isOn;
double price;
char letter;
String text;
\`\`\`
Это объявление — переменная появляется, но значения пока нет.

## 4. Присвоение значения
\`\`\`
int number = 100;
boolean isOn = true;
double price = 9.99;
char letter = 'C';
String text = "Java";
\`\`\`

## 5. Изменение переменной
После создания переменную можно изменить:
\`\`\`
int x = 5;
x = 10;
\`\`\`
Теперь значение \`x\` — \`10\`.

## 6. Вывод переменных
Переменные можно выводить в консоль:
\`\`\`
int age = 18;
System.out.println(age);
\`\`\`

## 7. Как работать с текстом + числами
Текст можно склеивать со значениями:
\`\`\`
String name = "Вася";
int age = 16;
System.out.println("Имя: " + name + ", возраст: " + age);
\`\`\`

## 8. Немного про \`boolean\`
Тип \`boolean\` хранит:
- \`true\` — истина
- \`false\` — ложь
\`\`\`
boolean isFinished = false;
\`\`\`

## 9. \`char\` — один символ
Для одного символа используются одинарные кавычки:
\`\`\`
char firstLetter = 'J';
\`\`\`
Если использовать двойные — будет строка:
\`\`\`
String text = "J"; // строка, а не char
\`\`\`

## 10. Начальное значение переменных
Переменные нужно инициализировать, прежде чем использовать.
Нельзя так:
\`\`\`
int x;
System.out.println(x); // ошибка
\`\`\`

## Итоги
- Переменная — имя для значения
- Каждый тип имеет своё назначение
- Строки — в двойных кавычках
- Символы — в одинарных кавычках
`;

