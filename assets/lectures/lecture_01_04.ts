const content = `
# Типы данных в Java

## Типы данных — это разные “форматы” значений

Java — **строго типизированный язык**.  
Это значит, что **каждой переменной обязательно указывается её тип**.

## Основные типы данных

### 1) \`int\` — целые числа
Хранит целые числа без дробной части:
\`\`\`
int a = 10;
int b = -5;
\`\`\`

### 2) \`double\` — дробные числа
Хранит числа с плавающей точкой (дробные):
\`\`\`
double pi = 3.14;
double temp = -10.5;
\`\`\`

### 3) \`boolean\` — булевый тип
Хранит **true** или **false**:
\`\`\`
boolean isAlive = true;
boolean isFinished = false;
\`\`\`

### 4) \`char\` — символ
Хранит **один символ**, в одинарных кавычках:
\`\`\`
char letter = 'A';
char digit = '5';
\`\`\`
Важно: **двойные кавычки — не подойдут**, только одинарные:
\`\`\`
char mistake = "A"; // ошибка
\`\`\`

### 5. \`String\` — строка текста
Не примитив, но очень важный тип для текста:
\`\`\`
String name = "JavaRush";
String text = "Hello, world!";
\`\`\`
Строки всегда в **двойных кавычках**.

## Объявление переменных
Чтобы **создать переменную**, указываем её тип и имя:
\`\`\`
int age;
double weight;
boolean isOpen;
String title;
\`\`\`

## Присвоение значения
Можно сразу задать значение:
\`\`\`
int age = 25;
double salary = 1234.56;
boolean isActive = true;
String message = "Привет!";
\`\`\`

## Изменение значения
Значение можно менять:
\`\`\`
int x = 10;
x = 20; // теперь x = 20
\`\`\`

## Вывод переменных
Переменные можно выводить:
\`\`\`
int age = 18;
System.out.println(age);
\`\`\`

## Склеивание значений со строкой
Можно вывести текст вместе с переменной:
\`\`\`
String name = "Вася";
int age = 16;

System.out.println("Имя: " + name + ", возраст: " + age);
\`\`\`

## Типы и совместимость
Нельзя сохранять в переменную тип, который не подходит:
\`\`\`
int number = 3.14; // ошибка
\`\`\`
Чтобы хранить дробное число, должен быть тип \`double\`.

## Примеры
\`\`\`
boolean isJavaCool = true;
char firstLetter = 'J';
double price = 99.99;
String greeting = "Hello!";
\`\`\`

## Итоги
- Переменная — это имя для значения
- Каждый тип данных подходит для своего вида значений
- Строки — в **двойных кавычках**
- Символы — в **одинарных**
- Java строго требует правильный тип данных
`;

